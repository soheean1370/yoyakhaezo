def starts_with_korean_particle(line: str) -> bool:
    """
    다음 줄이 조사로 시작하면 앞 줄과 붙인다.
    예:
    범위
    를
    -> 범위를
    """

    particles = [
        "은", "는", "이", "가",
        "을", "를", "의",
        "에", "에서", "에게", "께",
        "로", "으로",
        "와", "과", "랑", "하고",
        "도", "만",
        "부터", "까지",
        "보다", "처럼",
        "조차", "마저",
        "이나", "나",
        "라도", "이라도",
    ]

    line = line.strip()

    return any(
        re.match(rf"^{particle}(?=\s|[가-힣A-Za-z0-9])", line)
        for particle in particles
    )


def ends_with_connect_word(line: str) -> bool:
    """
    이전 줄이 연결어로 끝나면 다음 줄과 이어 붙인다.
    예:
    원금 및
    이자
    -> 원금 및 이자
    """

    connect_words = [
        "및",
        "또는",
        "혹은",
        "그리고",
        "또한",
        "다만",
        "단",
        "또",
        "아래",
        "다음",
        "관련",
        "포함",
        "제외",
    ]

    line = line.strip()

    return any(line.endswith(word) for word in connect_words)


def starts_with_connect_word(line: str) -> bool:
    """
    다음 줄이 연결어로 시작하면 앞 줄과 이어 붙인다.
    예:
    원금
    및 이자
    -> 원금 및 이자
    """

    connect_words = [
        "및",
        "또는",
        "혹은",
        "그리고",
        "또한",
        "다만",
        "단",
    ]

    line = line.strip()

    return any(
        re.match(rf"^{word}(?=\s|[가-힣A-Za-z0-9])", line)
        for word in connect_words
    )
    
def has_unclosed_parenthesis(text: str) -> bool:
    return text.count("(") > text.count(")")


def fix_broken_linebreaks(text: str) -> str:
    """
    PDF/OCR 줄바꿈 때문에 문장이나 단어가 끊긴 부분을 복구한다.

    처리 기준:
    - 괄호가 열려 있으면 닫힐 때까지 이어 붙인다.
    - 다음 줄이 조사로 시작하면 앞 줄에 붙인다.
      예: 범위 \n 를 -> 범위를
    - 이전 줄이 '및/또는/그리고' 같은 연결어로 끝나면 다음 줄과 이어 붙인다.
      예: 원금 및 \n 이자 -> 원금 및 이자
    - 다음 줄이 '및/또는/그리고' 같은 연결어로 시작해도 앞 줄과 이어 붙인다.
      예: 원금 \n 및 이자 -> 원금 및 이자
    - 구조 라인은 최대한 보존한다.
    """

    lines = text.split("\n")
    merged_lines = []
    buffer = ""

    for line in lines:
        line = line.strip()

        if not line:
            if buffer:
                merged_lines.append(buffer.strip())
                buffer = ""
            merged_lines.append("")
            continue

        # 괄호가 열려 있으면 닫힐 때까지 이어 붙임
        if buffer and has_unclosed_parenthesis(buffer):
            buffer += " " + line

            if not has_unclosed_parenthesis(buffer) and is_sentence_end(buffer):
                merged_lines.append(buffer.strip())
                buffer = ""

            continue

        # 다음 줄이 조사로 시작하면 앞 단어에 붙임
        # 예: 범위 \n 를 -> 범위를
        # 예: 사람 \n 의 -> 사람의
        if buffer and starts_with_korean_particle(line):
            buffer += line
            continue

        # 이전 줄이 연결어로 끝나면 다음 줄과 이어 붙임
        # 예: 기명피보험자 및 \n 기명1인 운전자 -> 기명피보험자 및 기명1인 운전자
        if buffer and ends_with_connect_word(buffer):
            buffer += " " + line
            continue

        # 다음 줄이 연결어로 시작하면 앞 줄과 이어 붙임
        # 예: 기명피보험자 \n 및 기명1인 운전자 -> 기명피보험자 및 기명1인 운전자
        if buffer and starts_with_connect_word(line):
            buffer += " " + line
            continue

        # 갱신형/특약/기본형처럼 단독으로 떨어진 보험 표 라벨은 앞 줄과 붙임
        if buffer and re.fullmatch(r"(갱\s*신\s*형|갱신형|특\s*약|특약|기\s*본\s*형|기본형)", line):
            buffer += " " + line
            continue

        # 구조 라인은 보존
        if is_structural_line(line):
            if buffer:
                merged_lines.append(buffer.strip())
                buffer = ""
            merged_lines.append(line)
            continue

        if not buffer:
            buffer = line
            continue

        # 이전 줄이 문장 끝이면 새 문장으로 분리
        if is_sentence_end(buffer):
            merged_lines.append(buffer.strip())
            buffer = line
        else:
            buffer += " " + line

    if buffer:
        merged_lines.append(buffer.strip())

    text = "\n".join(merged_lines)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


