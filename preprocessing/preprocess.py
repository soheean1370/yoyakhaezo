def process_file(input_path: Path, output_path: Path) -> None:
    with open(input_path, "r", encoding="utf-8") as f:
        raw_text = f.read()

    cleaned_text = preprocess_text(raw_text)

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(cleaned_text)

    sentence_count = count_cleaned_sentences(cleaned_text)
    print(f"{input_path.stem} -> 정제 문장 수: {sentence_count}")


def process_category(category: str) -> None:
    input_dir = INPUT_BASE_DIR / category
    output_dir = OUTPUT_BASE_DIR / category

    if not input_dir.exists():
        return

    txt_files = list(input_dir.glob("*.txt"))

    if not txt_files:
        return

    for input_path in txt_files:
        output_name = input_path.stem + "_cleaned.txt"
        output_path = output_dir / output_name
        process_file(input_path, output_path)


