# 1. 장식선 / 구분선 제거
# =========================================================

def remove_decoration_lines(text: str) -> str:
    """
    --- / === / *** / ___ 같은 의미 없는 장식선을 제거한다.
    단, 수식의 '-'나 상품명 안의 '-'는 보존한다.
    """

    lines = []

    for line in text.split("\n"):
        stripped = line.strip()

        if not stripped:
            lines.append("")
            continue

        if re.fullmatch(r"[-_=*~·.]{3,}", stripped):
            continue

        if re.fullmatch(r"[-_=*~·.\s]{3,}", stripped):
            continue

        lines.append(line)

    return "\n".join(lines)


