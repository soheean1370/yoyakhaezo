# 8. 쓸데없는 페이지 숫자 제거
# =========================================================

def remove_useless_page_numbers(text: str) -> str:
    cleaned_lines = []

    for line in text.split("\n"):
        line = line.strip()

        if not line:
            cleaned_lines.append("")
            continue

        if re.fullmatch(r"\d{4}\.\d{1,2}\.\d{1,2}\s+\d{1,2}:\d{2}(:\d{2})?", line):
            continue

        if re.fullmatch(r"\d{1,3}", line):
            continue

        if line in {"해당"}:
            continue

        if re.fullmatch(r"\d{1,3}\s*~", line):
            continue

        if re.fullmatch(r"\d{1,3}(\s+\d{1,3}){1,4}", line):
            continue

        line = re.sub(r"\b\d{1,3}\s*~(?=\s|$)", " ", line)
        line = re.sub(r"\b\d{1,3}\s*~\s*\d{1,3}\s*[pP]?\b", " ", line)
        line = re.sub(r"\(?\s*법령\s*참고\s*\d{1,3}쪽\s*\)?", " ", line)
        line = re.sub(r"(제\d+조(?:의\d+)?)\s*\d{1,3}쪽", r"\1", line)
        line = re.sub(r"\s*\d{1,3}쪽\)", ")", line)
        line = re.sub(r"\s*\d{1,3}쪽", " ", line)

        toc_like_patterns = [
            r"CONTENTS",
            r"목차",
            r"안내",
            r"가이드북",
            r"요약서",
            r"특별약관",
            r"보통약관",
            r"법조문",
            r"주요 보장",
            r"상대방",
            r"고객님",
            r"가해 차량",
            r"긴급",
            r"운전 가능자",
            r"자주 묻는 질문",
            r"보험용어",
            r"계약 내용",
            r"사고 시",
            r"보험 만기",
            r"보험료",
            r"증권상",
            r"약관",
            r"운전자",
            r"차량",
            r"자동차상해",
            r"교통상해",
            r"주행거리",
            r"커넥티드카",
            r"대중교통",
            r"장애인",
            r"반려동물",
            r"품질인증",
            r"녹색상품",
            r"보험료 납입",
        ]

        if any(re.search(pattern, line) for pattern in toc_like_patterns):
            line = re.sub(r"\s+\d{1,3}$", "", line)
            line = re.sub(
                r"(?<=[가-힣A-Za-z)])\s+\d{1,3}\s+(?=[가-힣A-Za-z])",
                " ",
                line,
            )

        line = re.sub(r"(\[\d+\]\s*[가-힣A-Za-z0-9\s]+특별약관)\s+\d{1,3}$", r"\1", line)
        line = re.sub(r"(-\s*[가-힣A-Za-z0-9\s()/·]+특별약관)\s+\d{1,3}$", r"\1", line)

        if re.fullmatch(r"\d{1,3}", line):
            continue

        line = re.sub(r"[ \t]{2,}", " ", line).strip()

        if line:
            cleaned_lines.append(line)

    text = "\n".join(cleaned_lines)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


