# 3. 웹페이지/크롤링 노이즈 제거
# =========================================================

def remove_webpage_noise(text: str) -> str:
    lines = []

    for line in text.split("\n"):
        line = line.strip()

        if not line:
            lines.append("")
            continue

        if re.fullmatch(r"\d{4}\.\d{1,2}\.\d{1,2}\s+\d{1,2}:\d{2}(:\d{2})?", line):
            continue

        ui_patterns = [
            r"신한카드\s*Mr\.?\s*Life\s*온라인\s*신청",
            r"카드\s*개\s*비교함\s*열기",
            r"비교함\s*열기",
            r"온라인\s*신청",
            r"카드\s*디자인",
        ]

        for pattern in ui_patterns:
            line = re.sub(pattern, " ", line, flags=re.IGNORECASE)

        if line.strip() in {
            "온라인 신청",
            "비교함 열기",
            "카드 개 비교함 열기",
            "카드 디자인",
        }:
            continue

        line = re.sub(r"[ \t]{2,}", " ", line).strip()

        if line:
            lines.append(line)

    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


