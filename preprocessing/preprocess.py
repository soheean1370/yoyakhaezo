# 5. 의미 없는 외계문자 라인 제거
# =========================================================

def remove_gibberish_lines(text: str) -> str:
    cleaned_lines = []

    for line in text.split("\n"):
        stripped = line.strip()

        if not stripped:
            cleaned_lines.append("")
            continue

        korean_count = len(re.findall(r"[가-힣]", stripped))
        english_count = len(re.findall(r"[A-Za-z]", stripped))
        digit_count = len(re.findall(r"\d", stripped))
        meaningful_count = korean_count + english_count + digit_count

        if meaningful_count == 0 and len(stripped) >= 2:
            continue

        if len(stripped) >= 5 and meaningful_count / len(stripped) < 0.2:
            continue

        cleaned_lines.append(line)

    return "\n".join(cleaned_lines)


