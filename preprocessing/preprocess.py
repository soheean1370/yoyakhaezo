def normalize_basic_text(text: str) -> str:
    lines = []

    for line in text.split("\n"):
        line = line.strip()
        line = re.sub(r"[ \t]{2,}", " ", line)
        lines.append(line)

    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


