# 2. PDF/OCR 기본 잡음 제거
# =========================================================

def remove_pdf_noise(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")

    text = re.sub(r"=+\s*PAGE\s*\d+\s*=+", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"^\s*-\s*\d+\s*-\s*$", "", text, flags=re.MULTILINE)

    text = re.sub(
        r"(?m)^\s*\d{1,3}\s+(?=("
        r"무배당|주\s*\d+\)|제\d+조|제\d+편|제\d+장|개인용|자동차|보험|"
        r"구\s*분|지급|계약|보통|특별약관|약관|상품|유의사항|목차|청년|"
        r"비과세|소득공제|고객|발급|가입|구분|내용|프로미카|상대방|운전|"
        r"용\s*어|대인배상|대물배상|자기신체|자기차량|무보험|긴급|주요|"
        r"쉽게|가해|사고|법조문|붙임|ISA|트래블로그|우리|KB|NH|농협|"
        r"신한|준법감시인"
        r"))",
        "",
        text,
    )

    text = re.sub(r"\b[pP]\.?\s*\d+\b", " ", text)
    text = re.sub(r"\b\d{1,3}\s*[pP]\b", " ", text)
    text = re.sub(r"\b\d{1,3}\s*~\s*\d{1,3}\s*[pP]\b", " ", text)
    text = re.sub(r"\b\d{1,3}\s*/\s*\d{1,3}\b", " ", text)
    text = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", " ", text)

    return text


