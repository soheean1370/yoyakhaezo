def apply_spacing_correction(text: str) -> str:
    if not USE_PYKOSPACING or not PYKOSPACING_AVAILABLE or spacing is None:
        return text

    corrected_lines = []

    for line in text.split("\n"):
        line = line.strip()

        if not line:
            corrected_lines.append("")
            continue

        if len(line) > 300:
            parts = re.split(r"(?<=[.!?다요함음])\s+", line)
            fixed_parts = []

            for part in parts:
                part = part.strip()

                if not part:
                    continue

                if len(part) > 300:
                    fixed_parts.append(part)
                    continue

                try:
                    fixed_parts.append(spacing(part))
                except Exception:
                    fixed_parts.append(part)

            corrected_lines.append(" ".join(fixed_parts))
            continue

        korean_count = len(re.findall(r"[가-힣]", line))
        digit_count = len(re.findall(r"\d", line))

        if korean_count < 5:
            corrected_lines.append(line)
            continue

        if digit_count >= korean_count and re.search(
            r"(연\s*\d|%|개월|만원|계약일수|경과일수|기본금리|약정금리|/365| x )",
            line,
        ):
            corrected_lines.append(line)
            continue

        if any(symbol in line for symbol in ["=", "/365", " x ", " + "]):
            corrected_lines.append(line)
            continue

        if is_structural_line(line):
            corrected_lines.append(line)
            continue

        try:
            corrected_lines.append(spacing(line))
        except Exception:
            corrected_lines.append(line)

    return "\n".join(corrected_lines)


