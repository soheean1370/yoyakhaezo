def normalize_bullets_and_symbols(text: str) -> str:
    text = re.sub(r"\s*(◇)", r"\n\1 ", text)
    text = re.sub(r"\s*(○)", r"\n\1 ", text)
    text = re.sub(r"\s*([①②③④⑤⑥⑦⑧⑨⑩])\s*", r"\n\1 ", text)

    text = re.sub(r"\s+(제\d+편)", r"\n\1", text)
    text = re.sub(r"\s+(제\d+장)", r"\n\1", text)
    text = re.sub(r"\s+(제\d+절)", r"\n\1", text)
    text = re.sub(r"\s+(제\d+조(?:의\d+)?\s*\([^)]+\))", r"\n\1", text)

    text = re.sub(r"\s+(\(\d+\))", r"\n\1", text)

    text = re.sub(r"\s+(<별표\s*\d+>)", r"\n\1", text)
    text = re.sub(r"\s+(<부표>)", r"\n\1", text)
    text = re.sub(r"\s+(<붙임>)", r"\n\1", text)
    text = re.sub(r"\s+(\[붙임\])", r"\n\1", text)

    text = re.sub(r"\s*◦\s*", "\n- ", text)
    text = re.sub(r"(?m)^\s*o\s+", "- ", text)

    text = re.sub(r"\s*(Q\))", r"\n\1", text)
    text = re.sub(r"\s*(A\))", r"\n\1", text)

    text = text.replace("“", "")
    text = text.replace("”", "")
    text = text.replace("‘", "")
    text = text.replace("’", "")

    return text.strip()


