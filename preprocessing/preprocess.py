# 7. 목차 점선 제거
# =========================================================

def remove_toc_dots(text: str) -> str:
    lines = []

    guide_noise_patterns = [
        r"시각화된\s*약관\s*요약서.*활용하시면",
        r"약관\s*핵심\s*체크항목\s*쉽게\s*찾기.*이용하시면",
        r"약관\s*내용\s*중\s*어려운\s*보험\s*용어",
        r"약관\s*본문\s*Bo\s*x",
        r"약관\s*본문\s*Box",
        r"약관\s*이해에\s*도움이\s*됩니다",
        r"프로미라이프\s*용어사전",
    ]

    for line in text.split("\n"):
        line = line.strip()

        if not line:
            lines.append("")
            continue

        line = re.sub(r"\s*[·.]{3,}\s*\d{1,4}\s*$", "", line)
        line = re.sub(r"\s*[·.]{3,}\s*$", "", line)
        line = re.sub(r"\s*[-_=~*]{3,}\s*$", "", line)

        if re.search(r"^(제\d+(편|장|절)|제\d+조|<별표|<부표|<붙임|\[붙임\])", line):
            line = re.sub(r"\s+\d{1,4}\s*$", "", line)

        line = line.strip()

        if any(re.search(pattern, line) for pattern in guide_noise_patterns):
            continue

        if line:
            lines.append(line)

    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


